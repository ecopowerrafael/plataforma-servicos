  INDEX `idb_whatsapp` (`whatsapp`),
  INDEX `idb_phone` (`phone`),
  INDEX `idb_tenant` (`tenant_id`),
  CONSTRAINT `fdb_category` FOREIGN KEY (`category_id`) REFERENCES `directory_categories`(`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `fdb_tenant` FOREIGN KEY (`tenant_id`) REFERENCES `tenants`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `directory_imports` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `public_id` CHAR(36) NOT NULL,
  `filename` VARCHAR(255) NOT NULL,
  `status` ENUM('ANALYZED','QUEUED','PROCESSING','PAUSED','COMPLETED','FAILED') NOT NULL DEFAULT 'ANALYZED',
  `total_found` INTEGER NOT NULL DEFAULT 0,
  `total_selected` INTEGER NOT NULL DEFAULT 0,
  `total_created` INTEGER NOT NULL DEFAULT 0,
  `total_updated` INTEGER NOT NULL DEFAULT 0,
  `total_unchanged` INTEGER NOT NULL DEFAULT 0,
  `total_duplicates` INTEGER NOT NULL DEFAULT 0,
  `processed_count` INTEGER NOT NULL DEFAULT 0,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `completed_at` DATETIME(3) NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `udi_public_id` (`public_id`),
  INDEX `idi_status_created` (`status`, `created_at`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `directory_import_items` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `import_id` BIGINT UNSIGNED NOT NULL,
  `category_id` BIGINT UNSIGNED NULL,
  `business_id` BIGINT UNSIGNED NULL,
  `source_local_id` VARCHAR(120) NULL,
  `category_detected` VARCHAR(160) NULL,
  `status` ENUM('CREATED','UPDATED','UNCHANGED','POSSIBLE_DUPLICATE','SKIPPED','ERROR') NOT NULL DEFAULT 'SKIPPED',
  `position` INTEGER NOT NULL,
  `source_data` JSON NOT NULL,
  `message` VARCHAR(500) NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `udi_import_position` (`import_id`, `position`),
  INDEX `idii_import_status` (`import_id`, `status`),
  CONSTRAINT `fdii_import` FOREIGN KEY (`import_id`) REFERENCES `directory_imports`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `fdii_category` FOREIGN KEY (`category_id`) REFERENCES `directory_categories`(`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `fdii_business` FOREIGN KEY (`business_id`) REFERENCES `directory_businesses`(`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
