  `source_segment_key` VARCHAR(120) NULL,
  `source_search_term` VARCHAR(160) NULL,
  `name` VARCHAR(180) NOT NULL,
  `slug` VARCHAR(180) NOT NULL,
  `city_slug` VARCHAR(180) NOT NULL,
  `raw_address` TEXT NOT NULL,
  `street` VARCHAR(180) NULL,
  `number` VARCHAR(32) NULL,
  `complement` VARCHAR(160) NULL,
  `neighborhood` VARCHAR(120) NULL,
  `city` VARCHAR(120) NOT NULL,
  `state` CHAR(2) NOT NULL,
  `postal_code` CHAR(8) NULL,
  `ibge_code` VARCHAR(16) NULL,
  `phone` VARCHAR(20) NULL,
  `whatsapp` VARCHAR(20) NULL,
  `email` VARCHAR(254) NULL,
  `website_url` VARCHAR(500) NULL,
  `image_url` VARCHAR(500) NULL,
  `source_url` VARCHAR(500) NULL,
  `relevance_score` INTEGER NULL,
  `review_status` VARCHAR(40) NULL,
  `active` BOOLEAN NOT NULL DEFAULT true,
  `indexable` BOOLEAN NOT NULL DEFAULT true,
  `source_hash` CHAR(64) NOT NULL,
  `first_imported_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `last_imported_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
