CREATE TABLE `directory_categories` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `public_id` CHAR(36) NOT NULL,
  `name` VARCHAR(120) NOT NULL,
  `singular_name` VARCHAR(120) NOT NULL,
  `plural_name` VARCHAR(120) NOT NULL,
  `slug` VARCHAR(120) NOT NULL,
  `description` TEXT NULL,
  `seo_title` VARCHAR(180) NULL,
  `seo_description` VARCHAR(320) NULL,
  `icon` VARCHAR(40) NULL,
  `active` BOOLEAN NOT NULL DEFAULT true,
  `indexable` BOOLEAN NOT NULL DEFAULT true,
  `sort_order` INTEGER NOT NULL DEFAULT 0,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE INDEX `udc_public_id` (`public_id`),
  UNIQUE INDEX `udc_slug` (`slug`),
  INDEX `idc_active_sort` (`active`, `sort_order`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

